#!/bin/bash
# Builds supabase/setup_all.sql = all migrations + seed, for pasting into the Supabase SQL Editor in one go.
# Re-run after adding a migration:  bash scripts/build_setup_sql.sh
set -e
cd "$(dirname "$0")/.."
OUT=supabase/setup_all.sql
{
  echo "-- KANZ CORNER EST. — complete database setup (generated by scripts/build_setup_sql.sh; do not edit)."
  echo "-- Paste into Supabase → SQL Editor → Run, ONCE, on a new empty project."
  for f in supabase/migrations/*.sql supabase/seed.sql; do echo; echo "-- ═════════ $(basename $f) ═════════"; cat "$f"; done
} > "$OUT"
echo "wrote $OUT ($(wc -l < $OUT) lines)"
