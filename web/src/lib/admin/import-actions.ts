"use server";
import fs from "node:fs";
import path from "node:path";
import { z } from "zod";
import { requireAdmin, requireStaff } from "@/lib/auth";
import { createClient } from "@/lib/supabase/server";
import { audit, fail, ok, refreshStorefront, uniqueSlug, type Result } from "./common";
import { revalidatePath } from "next/cache";

interface PkgItem {
  key: string; batch: "pdf" | "legacy"; name_en: string; name_ar: string | null; category_slug: string; source_page: number | null; image: string | null;
  extra_images: string[]; description_en: string | null; specs: Record<string, string[]>; flags: string[]; review_note: string | null; document?: { title: string; image: string };
}
const BATCHES = {
  pdf: "Uploaded catalogue PDF (kanz-CATALOGE.pdf, 10 pages)",
  legacy: "Earlier WordPress extraction — items NOT found in the uploaded PDF",
} as const;
const DATA_DIR = () => path.join(process.cwd(), "data", "catalogue-import");

/** Loads the extracted catalogue package into the staging tables + private bucket. Nothing is published. */
export async function loadCatalogueExtraction(): Promise<Result<{ created: string[]; skipped: string[] }>> {
  const user = await requireStaff();
  const sb = await createClient();
  let pkg: { items: PkgItem[] };
  try { pkg = JSON.parse(fs.readFileSync(path.join(DATA_DIR(), "import.json"), "utf8")); } catch { return fail("Extraction package not found on the server (web/data/catalogue-import/import.json)."); }

  const created: string[] = [], skipped: string[] = [];
  for (const kind of ["pdf", "legacy"] as const) {
    const items = pkg.items.filter((i) => i.batch === kind);
    const { data: existing } = await sb.from("import_batches").select("id").eq("source_name", BATCHES[kind]).maybeSingle();
    if (existing) { skipped.push(BATCHES[kind]); continue; }
    const { data: batch, error } = await sb.from("import_batches").insert({ source_name: BATCHES[kind], created_by: user.id, notes: `${items.length} items. Generated by scripts/build_import.py. UNVERIFIED — review before publishing.` }).select("id").single();
    if (error || !batch) return fail(error?.message ?? "Could not create batch");

    const uploaded = new Map<string, string>();
    const up = async (file: string | null | undefined) => {
      if (!file) return null;
      if (uploaded.has(file)) return uploaded.get(file)!;
      const dest = `${batch.id}/${file.replace(/\//g, "_")}`;
      const buf = fs.readFileSync(path.join(DATA_DIR(), "images", file));
      const { error: e } = await sb.storage.from("import-staging").upload(dest, buf, { contentType: "image/jpeg", upsert: true });
      if (e) throw new Error(`Upload failed for ${file}: ${e.message}`);
      uploaded.set(file, dest); return dest;
    };
    try {
      const rows = [];
      for (const it of items) {
        rows.push({
          batch_id: batch.id, source_page: it.source_page, name_en: it.name_en, name_ar: it.name_ar, suggested_category_slug: it.category_slug,
          description_en: it.description_en, specs: it.specs, image_path: await up(it.image), flags: it.flags, review_note: it.review_note,
          extra: { key: it.key, images: await Promise.all((it.extra_images ?? []).map(up)), document: it.document ? { title: it.document.title, path: await up(it.document.image) } : null },
        });
      }
      const { error: ie } = await sb.from("import_items").insert(rows);
      if (ie) throw new Error(ie.message);
    } catch (e) { await sb.from("import_batches").delete().eq("id", batch.id); return fail((e as Error).message); }
    created.push(`${BATCHES[kind]} (${items.length})`);
  }
  await audit(sb, user.id, "import.load", "import_batches", undefined, { created, skipped });
  revalidatePath("/admin/import");
  return ok({ created, skipped });
}

const itemSchema = z.object({
  name_en: z.string().trim().min(1).max(200), name_ar: z.string().trim().max(200).nullable(), suggested_category_slug: z.string().trim().max(100).nullable(),
  description_en: z.string().trim().max(5000).nullable(), review_note: z.string().trim().max(5000).nullable(),
  specs: z.record(z.string(), z.array(z.string().trim().min(1).max(200)).max(80)), image_path: z.string().max(300).nullable(),
});

export async function updateImportItem(id: string, input: z.input<typeof itemSchema>): Promise<Result> {
  const user = await requireStaff();
  const parsed = itemSchema.safeParse(input);
  if (!parsed.success) return fail("Please check the fields (name is required).");
  const sb = await createClient();
  const { error } = await sb.from("import_items").update({ ...parsed.data, reviewed_by: user.id, reviewed_at: new Date().toISOString() }).eq("id", id).neq("status", "published");
  if (error) return fail(error.message);
  revalidatePath("/admin/import", "layout");
  return ok(null);
}

/** Approve/reject/reset. Items with third-party branding are NOT approved in bulk unless the reviewer confirmed (acknowledgeFlags). */
export async function setImportStatus(ids: string[], status: "pending" | "approved" | "rejected", acknowledgeFlags = false): Promise<Result<{ changed: number; blocked: string[] }>> {
  const user = await requireStaff();
  if (!ids.length) return fail("Select at least one item.");
  const sb = await createClient();
  let targets = ids; const blocked: string[] = [];
  if (status === "approved" && !acknowledgeFlags) {
    const { data } = await sb.from("import_items").select("id, name_en, flags").in("id", ids);
    const bad = (data ?? []).filter((r) => (r.flags as string[]).includes("foreign_branding"));
    bad.forEach((r) => blocked.push(r.name_en));
    targets = ids.filter((id) => !bad.some((r) => r.id === id));
  }
  if (!targets.length) return ok({ changed: 0, blocked });
  const { data, error } = await sb.from("import_items").update({ status, reviewed_by: user.id, reviewed_at: new Date().toISOString() }).in("id", targets).neq("status", "published").select("id");
  if (error) return fail(error.message);
  revalidatePath("/admin/import", "layout");
  return ok({ changed: data?.length ?? 0, blocked });
}

async function copyObject(sb: Awaited<ReturnType<typeof createClient>>, from: { bucket: string; path: string }, to: { bucket: string; path: string }) {
  const { data, error } = await sb.storage.from(from.bucket).download(from.path);
  if (error || !data) throw new Error(`Could not read ${from.path}: ${error?.message}`);
  const { error: ue } = await sb.storage.from(to.bucket).upload(to.path, data, { contentType: data.type || "image/jpeg", upsert: true });
  if (ue) throw new Error(`Could not write ${to.path}: ${ue.message}`);
}

/** Turns approved items into DRAFT, quote-only product families. They still need an explicit "Publish" in Products. */
export async function publishImportItems(ids: string[]): Promise<Result<{ published: number; errors: string[] }>> {
  const user = await requireStaff();
  const sb = await createClient();
  const { data: items } = await sb.from("import_items").select("*").in("id", ids).eq("status", "approved");
  if (!items?.length) return fail("No approved items selected.");
  const [{ data: cats }, { data: defs }] = await Promise.all([sb.from("categories").select("id, slug"), sb.from("attribute_defs").select("id, key")]);
  const catId = new Map((cats ?? []).map((c) => [c.slug, c.id]));
  const defId = new Map((defs ?? []).map((d) => [d.key, d.id]));
  let published = 0; const errors: string[] = [];

  for (const it of items) {
    let createdId: string | null = null;
    try {
      const slug = await uniqueSlug(sb, "products", it.name_en);
      const { data: product, error } = await sb.from("products").insert({
        slug, name_en: it.name_en, name_ar: it.name_ar, description_en: it.description_en, category_id: catId.get(it.suggested_category_slug ?? "") ?? null,
        status: "draft", is_quote_only: true, source_page: it.source_page, sku: it.suggested_sku,
      }).select("id").single();
      if (error || !product) throw new Error(error?.message ?? "insert failed");
      createdId = product.id;

      const attrRows = Object.entries((it.specs ?? {}) as Record<string, string[]>).flatMap(([k, vals]) => {
        const attribute_id = defId.get(k); if (!attribute_id) return [];
        return [...new Set(vals)].map((value_en, i) => ({ product_id: product.id, attribute_id, value_en, sort_order: i }));
      });
      if (attrRows.length) { const { error: ae } = await sb.from("product_attribute_values").insert(attrRows); if (ae) throw new Error(ae.message); }

      const imgs: string[] = [it.image_path, ...((it.extra?.images as string[]) ?? [])].filter(Boolean);
      for (let n = 0; n < imgs.length; n++) {
        const dest = `${product.id}/${n}-${path.basename(imgs[n])}`;
        await copyObject(sb, { bucket: "import-staging", path: imgs[n] }, { bucket: "product-images", path: dest });
        await sb.from("product_images").insert({ product_id: product.id, storage_path: dest, sort_order: n, is_primary: n === 0, needs_hires: (it.flags as string[]).includes("low_res"), alt_en: it.name_en });
      }
      const doc = it.extra?.document as { title: string; path: string } | null;
      if (doc?.path) {
        const dest = `${product.id}/${path.basename(doc.path)}`;
        await copyObject(sb, { bucket: "import-staging", path: doc.path }, { bucket: "product-docs", path: dest });
        await sb.from("product_documents").insert({ product_id: product.id, kind: "datasheet", title: doc.title, storage_path: dest, is_public: true });
      }
      await sb.from("import_items").update({ status: "published", published_product_id: product.id }).eq("id", it.id);
      await audit(sb, user.id, "import.publish_item", "products", product.id, { import_item: it.id });
      published++;
    } catch (e) {
      // All-or-nothing per item: remove the half-created product (children cascade) so a retry cannot create duplicates.
      if (createdId) { await sb.from("products").delete().eq("id", createdId); await sb.storage.from("product-images").remove((await sb.storage.from("product-images").list(createdId)).data?.map((f) => `${createdId}/${f.name}`) ?? []); }
      errors.push(`${it.name_en}: ${(e as Error).message}`);
    }
  }
  revalidatePath("/admin/import", "layout"); revalidatePath("/admin/products"); refreshStorefront();
  return ok({ published, errors });
}

export async function deleteImportBatch(batchId: string): Promise<Result> {
  await requireAdmin();
  const sb = await createClient();
  const { data: files } = await sb.storage.from("import-staging").list(batchId, { limit: 1000 });
  if (files?.length) await sb.storage.from("import-staging").remove(files.map((f) => `${batchId}/${f.name}`));
  const { error } = await sb.from("import_batches").delete().eq("id", batchId);
  if (error) return fail(error.message);
  revalidatePath("/admin/import");
  return ok(null);
}
